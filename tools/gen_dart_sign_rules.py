#!/usr/bin/env python3
"""Generates protocol/dart/lib/src/sign_rules_data.dart from docs/contract/sign-rules.json.

    python tools/gen_dart_sign_rules.py            # rewrite
    python tools/gen_dart_sign_rules.py --check    # exit 1 if the committed file differs
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "docs", "contract", "sign-rules.json")
OUT = os.path.join(HERE, "..", "protocol", "dart", "lib", "src", "sign_rules_data.dart")


def dstr(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def render() -> str:
    d = json.load(open(SRC, encoding="utf-8"))
    o = ["// GENERATED by tools/gen_dart_sign_rules.py from docs/contract/sign-rules.json.",
         "// Do not edit; change the JSON and regenerate.",
         "library;", "",
         "/// One vendored sign: VzNr, wire code, official German name, and the column it goes in.",
         "class SignInfo {",
         "  const SignInfo(this.vzNr, this.code, this.labelDe, this.left);",
         "  final String vzNr;",
         "  final int code;",
         "  final String labelDe;",
         "  final bool left;",
         "}", "",
         f"const int signRulesDisplayedPerColumn = {d['wire']['displayedSignsPerColumn']};", "",
         "const List<SignInfo> vendoredSigns = <SignInfo>["]
    for s in d["signs"]:
        o.append(f"  SignInfo({dstr(s['vzNr'])}, {s['code']}, {dstr(s['labelDe'])}, "
                 f"{'true' if s['side'] == 'left' else 'false'}),")
    o.append("];")
    o.append("")
    o.append("/// Signs that cannot stand together: adding one removes the others of its family.")
    o.append("const Map<String, List<String>> signFamilies = <String, List<String>>{")
    for k, v in d["families"].items():
        o.append(f"  {dstr(k)}: <String>[{', '.join(dstr(x) for x in v)}],")
    o.append("};")
    o.append("")
    o.append("/// Adding the key also removes every sign whose major VzNr is listed.")
    o.append("const Map<String, List<String>> signCancels = <String, List<String>>{")
    for k, v in d["cancels"].items():
        o.append(f"  {dstr(k)}: <String>[{', '.join(dstr(x) for x in v)}],")
    o.append("};")
    return "\n".join(o) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8", newline="").read().replace("\r\n", "\n") if os.path.exists(OUT) else ""
        if cur != text:
            print("sign_rules_data.dart is out of date: run tools/gen_dart_sign_rules.py")
            sys.exit(1)
        print("sign_rules_data.dart up to date")
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
