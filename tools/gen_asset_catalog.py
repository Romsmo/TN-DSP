#!/usr/bin/env python3
"""Generate the C++ catalog that maps traffic-sign codes / icon names to the
LVGL image descriptors produced by tools/gen_assets.sh.

Sign code (wire + catalog key): packed uint16 = major*100 + minor  (minor 0 = bare).
  "142-10" -> 14210    "101-51" -> 10151    "276" -> 27600
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).parent.parent
SIGNS = ROOT / "ui/assets/signs"
ICONS = ROOT / "ui/assets/icons"
MANIFEST = json.loads((ROOT / "tools/signs/manifest.json").read_text(encoding="utf-8"))


def sign_code(vznr: str) -> int:
    parts = vznr.split("-")
    major = int(parts[0])
    minor = int(parts[1]) if len(parts) > 1 else 0
    return major * 100 + minor


def gen_signs():
    idx = {}
    for line in (SIGNS / "_index.txt").read_text().splitlines():
        vznr, var = line.split()
        idx[vznr] = var
    group = {m["vznr"]: m["group"] for m in MANIFEST}

    rows = []
    for vznr, var in sorted(idx.items(), key=lambda kv: sign_code(kv[0])):
        g = "Danger" if group.get(vznr) == "danger" else "Prohibition"
        rows.append((sign_code(vznr), var, g, vznr))

    h = ["// generated by tools/gen_asset_catalog.py - do not edit", "#pragma once",
         "#include <cstdint>", '#include "lvgl.h"', "",
         "namespace ui::assets {", "",
         "enum class SignGroup : uint8_t { Danger, Prohibition };", "",
         "// code = major*100 + minor (e.g. 142-10 -> 14210). Returns nullptr if unknown.",
         "const lv_image_dsc_t* sign(uint16_t code);",
         "bool sign_group(uint16_t code, SignGroup& out);",
         "int  sign_count();",
         "uint16_t sign_code_at(int i);", "",
         "}  // namespace ui::assets", ""]
    (SIGNS / "sign_catalog.h").write_text("\n".join(h), encoding="utf-8")

    c = ["// generated by tools/gen_asset_catalog.py - do not edit",
         '#include "ui/assets/signs/sign_catalog.h"', ""]
    for _, var, _, _ in rows:
        c.append(f"LV_IMAGE_DECLARE({var});")
    c += ["", "namespace ui::assets {", "namespace {", "",
          "struct Entry { uint16_t code; const lv_image_dsc_t* img; SignGroup group; };",
          "constexpr Entry kSigns[] = {"]
    for code, var, g, vznr in rows:
        c.append(f"    {{ {code:5}, &{var}, SignGroup::{g} }},  // {vznr}")
    c += ["};", "constexpr int kCount = int(sizeof(kSigns) / sizeof(kSigns[0]));", "",
          "const Entry* find(uint16_t code) {",
          "    int lo = 0, hi = kCount - 1;",
          "    while (lo <= hi) {",
          "        int mid = (lo + hi) / 2;",
          "        if (kSigns[mid].code == code) return &kSigns[mid];",
          "        if (kSigns[mid].code < code) lo = mid + 1; else hi = mid - 1;",
          "    }",
          "    return nullptr;",
          "}", "", "}  // namespace", "",
          "const lv_image_dsc_t* sign(uint16_t code) {",
          "    const Entry* e = find(code);",
          "    return e ? e->img : nullptr;",
          "}",
          "bool sign_group(uint16_t code, SignGroup& out) {",
          "    const Entry* e = find(code);",
          "    if (!e) return false;",
          "    out = e->group;",
          "    return true;",
          "}",
          "int sign_count() { return kCount; }",
          "uint16_t sign_code_at(int i) { return (i >= 0 && i < kCount) ? kSigns[i].code : 0; }", "",
          "}  // namespace ui::assets", ""]
    (SIGNS / "sign_catalog.cpp").write_text("\n".join(c), encoding="utf-8")
    return len(rows)


def gen_icons():
    names = []
    for line in (ICONS / "_index.txt").read_text().splitlines():
        name, var = line.split()
        names.append((name, var))

    def enum_name(n):
        return "".join(p.capitalize() for p in re.split(r"[-_]", n))

    h = ["// generated by tools/gen_asset_catalog.py - do not edit", "#pragma once",
         '#include "lvgl.h"', "", "namespace ui::assets {", "",
         "enum class Icon {"]
    for name, _ in names:
        h.append(f"    {enum_name(name)},")
    h += ["    _Count,", "};", "",
          "// A8 glyph; recolour at the call site via image_recolor / recolor_opa.",
          "const lv_image_dsc_t* icon(Icon ic);", "",
          "}  // namespace ui::assets", ""]
    (ICONS / "icons.h").write_text("\n".join(h), encoding="utf-8")

    c = ["// generated by tools/gen_asset_catalog.py - do not edit",
         '#include "ui/assets/icons/icons.h"', ""]
    for _, var in names:
        c.append(f"LV_IMAGE_DECLARE({var});")
    c += ["", "namespace ui::assets {", "",
          "const lv_image_dsc_t* icon(Icon ic) {",
          "    switch (ic) {"]
    for name, var in names:
        c.append(f"        case Icon::{enum_name(name)}: return &{var};")
    c += ["        default: return nullptr;",
          "    }",
          "}", "", "}  // namespace ui::assets", ""]
    (ICONS / "icons.cpp").write_text("\n".join(c), encoding="utf-8")
    return len(names)


if __name__ == "__main__":
    ns = gen_signs()
    ni = gen_icons()
    print(f"catalog: {ns} signs, {ni} icons")
