#!/usr/bin/env python3
"""Generate the event-chime WAVs (16-bit PCM mono, 16 kHz) into tools/audio/tones/
and emit the flash fallback C array (core/audio/fallback_tones.cpp).

    python tools/gen_audio_tones.py
"""
import math
import struct
import wave
from pathlib import Path

ROOT = Path(__file__).parent.parent
OUT = ROOT / "tools/audio/tones"
CPP = ROOT / "core/audio/fallback_tones.cpp"
SR = 16000


def tone(freqs, dur_s, gain=0.5):
    """freqs: list of (start_hz, end_hz, weight) played together, linear sweep."""
    n = int(SR * dur_s)
    out = []
    for i in range(n):
        t = i / SR
        env = min(1.0, t / 0.01, (dur_s - t) / 0.02)   # 10 ms attack / 20 ms release
        s = 0.0
        for f0, f1, w in freqs:
            f = f0 + (f1 - f0) * (t / dur_s)
            s += w * math.sin(2 * math.pi * f * t)
        out.append(int(max(-1.0, min(1.0, gain * env * s)) * 32767))
    return out


def seq(*segments):
    s = []
    for seg in segments:
        s.extend(seg)
    return s


CLIPS = {
    "warn":    seq(tone([(880, 880, 1.0)], 0.14), [0] * int(SR * 0.05),
                   tone([(660, 660, 1.0)], 0.18)),
    "alert":   seq(tone([(1000, 1000, 1.0)], 0.09), [0] * int(SR * 0.04),
                   tone([(1000, 1000, 1.0)], 0.09), [0] * int(SR * 0.04),
                   tone([(1200, 1200, 1.0)], 0.12)),
    "confirm": seq(tone([(700, 700, 1.0)], 0.10), [0] * int(SR * 0.05),
                   tone([(700, 700, 1.0)], 0.10)),
    "info":    tone([(760, 760, 1.0)], 0.16),
    "clear":   seq(tone([(600, 600, 1.0)], 0.12), [0] * int(SR * 0.03),
                   tone([(900, 900, 1.0)], 0.16)),
}


def write_wav(path, samples):
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(b"".join(struct.pack("<h", s) for s in samples))


def emit_cpp(fallbacks):
    lines = [
        "// generated by tools/gen_audio_tones.py - do not edit",
        '#include "core/audio/clips.h"', "",
        "#include <cstddef>", "#include <cstdint>", "",
        "namespace core::audio {", "",
    ]
    for name, samples in fallbacks.items():
        lines.append(f"static const int16_t kTone_{name}[] = {{")
        for i in range(0, len(samples), 16):
            lines.append("    " + ",".join(str(s) for s in samples[i:i + 16]) + ",")
        lines.append("};")
        lines.append("")
    lines += [
        "const int16_t* fallback_pcm(Clip c, size_t& n) {",
        "    switch (c) {",
    ]
    for name in fallbacks:
        enum = "ToneWarn" if name == "warn" else "ToneInfo"
        lines.append(f"        case Clip::{enum}: n = sizeof(kTone_{name}) / 2; return kTone_{name};")
    lines += [
        "        default: n = 0; return nullptr;",
        "    }",
        "}", "", "}  // namespace core::audio", "",
    ]
    CPP.write_text("\n".join(lines), encoding="utf-8")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, samples in CLIPS.items():
        write_wav(OUT / f"{name}.wav", samples)
    emit_cpp({"warn": CLIPS["warn"], "info": CLIPS["info"]})
    print(f"wrote {len(CLIPS)} tones to {OUT} and {CPP.name}")


if __name__ == "__main__":
    main()
